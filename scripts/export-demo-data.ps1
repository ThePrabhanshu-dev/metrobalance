<#
.SYNOPSIS
    Exports the in-memory demo dataset into a static JavaScript file for the public demo.

.DESCRIPTION
    The .NET application cannot be hosted on a free tier without an account, so the
    shareable public link is a static, browser-only copy of the app. To keep that copy
    honest it is generated from the *live* Web API responses (not hand-written), so the
    numbers shown to DMRC are exactly what /api/cards returns.

    This script calls the running application and writes:
      src\MetroBalance.Web\wwwroot\demo\demo-data.js

    It captures:
      * the enquiry payload of every demo card (balance + recharges + journeys),
      * the raw API envelopes for balance / statement / amount (shown as "raw API response"),
      * the official DMRC guidance, split into the card-kind-specific first step so the
        static demo can reproduce CardNumberClassifier behaviour exactly.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\export-demo-data.ps1 -BaseUrl http://localhost:5080
#>
[CmdletBinding()]
param(
    [string]$BaseUrl = 'http://localhost:5080',
    [string]$ProjectRoot
)

$ErrorActionPreference = 'Stop'

if (-not $ProjectRoot) {
    $ProjectRoot = Split-Path -Parent $PSScriptRoot
}

$outputPath = Join-Path $ProjectRoot 'src\MetroBalance.Web\wwwroot\demo\demo-data.js'

function Get-Json {
    param([string]$Url)
    $response = Invoke-RestMethod -Uri $Url -Method Get -Headers @{ Accept = 'application/json' }
    if ($response.success -ne $true) {
        throw "API call failed for '$Url': $($response.message)"
    }
    return $response
}

Write-Host "Reading demo dataset from $BaseUrl ..." -ForegroundColor Cyan

$demoNumbers = (Get-Json "$BaseUrl/api/cards/demo-numbers").data
if (-not $demoNumbers -or $demoNumbers.Count -eq 0) {
    throw 'No demo card numbers were returned by the API.'
}

$cards = [ordered]@{}
foreach ($number in $demoNumbers) {
    $encoded = [System.Uri]::EscapeDataString($number)
    $enquiry = (Get-Json "$BaseUrl/api/cards/$encoded/enquiry").data
    $cards[$number] = $enquiry
    Write-Host "  captured $number ($($enquiry.cardStatus))" -ForegroundColor DarkGray
}

# Raw envelopes - these are what DMRC would see if they called the API themselves.
$sample = $demoNumbers[0]
$sampleEncoded = [System.Uri]::EscapeDataString($sample)
$rawSamples = [ordered]@{
    balance     = Get-Json "$BaseUrl/api/cards/$sampleEncoded/balance"
    statement   = Get-Json "$BaseUrl/api/cards/$sampleEncoded/statement"
    amount      = Get-Json "$BaseUrl/api/cards/$sampleEncoded/amount"
    enquiry     = Get-Json "$BaseUrl/api/cards/$sampleEncoded/enquiry"
    demoNumbers = Get-Json "$BaseUrl/api/cards/demo-numbers"
}

# The guidance the API produces depends on the card kind. Three probes give us the
# shared base steps plus the two card-kind-specific first steps.
$engraved = (Get-Json "$BaseUrl/api/cards/1234567890/enquiry").data
$smartCard = (Get-Json "$BaseUrl/api/cards/123456789012/enquiry").data
$bankStyle = (Get-Json "$BaseUrl/api/cards/8177769600175160/enquiry").data
$unknown = (Get-Json "$BaseUrl/api/cards/ABCDEF/enquiry").data

$baseSteps = @($smartCard.steps)
$basePolicy = [string]$smartCard.policyNote
$bankPolicy = [string]$bankStyle.policyNote
$bankPolicySuffix = if ($bankPolicy.Length -gt $basePolicy.Length) {
    $bankPolicy.Substring($basePolicy.Length).Trim()
} else {
    ''
}

$guidance = [ordered]@{
    dataSource        = [string]$bankStyle.dataSource
    basePolicy        = $basePolicy
    bankPolicySuffix  = $bankPolicySuffix
    baseSteps         = $baseSteps
    engravedFirstStep = [string]$engraved.steps[0]
    bankFirstStep     = [string]$bankStyle.steps[0]
    officialLinks     = $bankStyle.officialLinks
    cardKind          = [ordered]@{
        unknown      = [string]$unknown.cardKindDescription
        engravedId   = [string]$engraved.cardKindDescription
        smartCard    = [string]$smartCard.cardKindDescription
        bankStyle    = [string]$bankStyle.cardKindDescription
    }
}

$payload = [ordered]@{
    capturedAtUtc = (Get-Date).ToUniversalTime().ToString('o')
    sourceApi     = $BaseUrl
    demoNumbers   = @($demoNumbers)
    cards         = $cards
    guidance      = $guidance
    rawSamples    = $rawSamples
}

$json = $payload | ConvertTo-Json -Depth 12 -Compress

# Round-trip check: the file must be valid JSON inside the JS wrapper.
$null = $json | ConvertFrom-Json

$directory = Split-Path -Parent $outputPath
if (-not (Test-Path $directory)) {
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
}

$content = @"
/* MetroBalance public demo dataset - generated by scripts/export-demo-data.ps1.
   Do not edit by hand: re-run the script to refresh it.

   Every amount below is SIMULATED DEMO DATA produced by the in-memory
   MockMetroCardProvider. Nothing here is a live DMRC record. */
window.METROBALANCE_DEMO_DATA = $json;
"@

Set-Content -Path $outputPath -Value $content -Encoding UTF8

$size = (Get-Item $outputPath).Length
Write-Host "Wrote $outputPath ($size bytes)" -ForegroundColor Green
